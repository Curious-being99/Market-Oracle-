// 5. OANDA Live Client Spot FX Order Book Proxy
app.post("/api/live-oanda", async (req, res) => {
  const { token, accountId, env, instrument } = req.body;

  if (!token || !accountId || !instrument) {
    return res.status(400).json({ error: "Missing required parameters: token, accountId, and instrument are required." });
  }

  const host = env === "live" ? "api-fxtrade.oanda.com" : "api-fxpractice.oanda.com";
  const url = `https://${host}/v3/instruments/${instrument}/orderBook`;

  try {
    const response = await fetchWithProxy(url, {
      headers: {
        "Authorization": `Bearer ${token}`,
        "Content-Type": "application/json"
      }
    });

    if (!response.ok) {
      const errMsg = await response.text();
      return res.status(response.status).json({ error: `OANDA Error (${response.status}): ${errMsg}` });
    }

    const data: any = await response.json();
    const orderBook = data.orderBook;

    if (!orderBook || !orderBook.buckets) {
      return res.status(500).json({ error: "Invalid OANDA response format: orderBook buckets not found in response payload." });
    }

    // Map OANDA buckets to Sovereign DOM structure
    const buckets = orderBook.buckets;
    const midPrice = parseFloat(orderBook.price);
    const decimals = instrument.includes("JPY") ? 3 : 5;

    // Filter buckets into Bids (below mid) and Asks (above mid)
    const bids: Array<{ price: number; size: number; mySize: number }> = [];
    const asks: Array<{ price: number; size: number; mySize: number }> = [];

    buckets.forEach((b: any) => {
      const price = parseFloat(b.price);
      // OANDA provides order/count percentages (e.g., 0.2500)
      const buyerSum = parseFloat(b.longOrderPercent) + parseFloat(b.longCountPercent);
      const sellerSum = parseFloat(b.shortOrderPercent) + parseFloat(b.shortCountPercent);

      const sizeFactor = 10000; // standard multiplier to produce readable "lots"

      if (price < midPrice) {
        bids.push({
          price,
          size: Math.round(buyerSum * sizeFactor) || 5,
          mySize: 0
        });
      } else {
        asks.push({
          price,
          size: Math.round(sellerSum * sizeFactor) || 5,
          mySize: 0
        });
      }
    });

    // Sort asks ascending, bids descending
    asks.sort((a, b) => a.price - b.price);
    bids.sort((a, b) => b.price - a.price);

    // Limit to top levels for Depth of Market representation
    const finalAsks = asks.slice(0, 15).reverse(); // top asks closest to mid at the bottom of asks array
    const finalBids = bids.slice(0, 15);

    res.json({
      symbol: instrument,
      price: midPrice,
      decimals,
      time: orderBook.time,
      dom: {
        bids: finalBids,
        asks: finalAsks
      }
    });

  } catch (error: any) {
    console.error("OANDA API Proxy Exception:", error);
    res.status(500).json({ error: `OANDA Proxy connection crashed: ${error.message}` });
  }
});

