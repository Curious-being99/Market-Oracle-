// Safe wrapper for HttpsProxyAgent that attaches error listeners to all created sockets
// preventing unhandled socket or TLS context disconnect errors from leaking to uncaughtException
function createSafeHttpsProxyAgent(proxyUrl: string): any {
  const agent = new HttpsProxyAgent(proxyUrl);
  
  const originalConnect = (agent as any).connect;
  if (typeof originalConnect === 'function') {
    (agent as any).connect = async function(req: any, opts: any) {
      try {
        const socket = await originalConnect.call(this, req, opts);
        if (socket && typeof socket.on === 'function') {
          socket.on('error', (err: any) => {
            // Absorb expected connection errors on transient sockets quietly
          });
        }
        return socket;
      } catch (err: any) {
        throw err;
      }
    };
  }
  
  const originalCreateConnection = (agent as any).createConnection;
  if (typeof originalCreateConnection === 'function') {
    (agent as any).createConnection = function(configuration: any, callback: any) {
      try {
        const socket = originalCreateConnection.call(this, configuration, callback);
        if (socket && typeof socket.on === 'function') {
          socket.on('error', (err: any) => {
            // Absorb expected connection errors on transient sockets quietly
          });
        }
        return socket;
      } catch (err: any) {
        throw err;
      }
    };
  }

  const originalCallback = (agent as any).callback;
  if (typeof originalCallback === 'function') {
    (agent as any).callback = async function(req: any, opts: any) {
      try {
        const socket = await originalCallback.call(this, req, opts);
        if (socket && typeof socket.on === 'function') {
          socket.on('error', (err: any) => {
            // Absorb expected connection errors on transient sockets quietly
          });
        }
        return socket;
      } catch (err: any) {
        throw err;
      }
    };
  }

  return agent;
}

