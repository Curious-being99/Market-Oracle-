// Quietly check system outbound proxy settings on startup to ensure instant routing response
async function verifySystemProxyQuietly() {
  const defaultProxy = process.env.PROXY_URL || process.env.HTTP_PROXY;
  if (!defaultProxy || !isValidProxyUrl(defaultProxy)) {
    isSystemProxyBroken = true;
    return;
  }
  
  try {
    const url = new URL("https://api.ipify.org?format=json");
    const agent = createSafeHttpsProxyAgent(defaultProxy);
    const reqOpts = {
      method: "GET",
      agent: agent,
      timeout: 1500
    };
    
    await new Promise<void>((resolve, reject) => {
      const req = https.request(url, reqOpts, (res: any) => {
        if (res.statusCode >= 200 && res.statusCode < 300) {
          resolve();
        } else {
          reject(new Error(`Status ${res.statusCode}`));
        }
      });
      req.on("socket", (socket) => {
        socket.on("error", (err: any) => {
          reject(err);
        });
      });
      req.on("error", reject);
      req.on("timeout", () => {
        req.destroy();
        reject(new Error("Timeout"));
      });
      req.end();
    });
    
    console.log(`[PROXY STATUS] Outbound route validated successfully: ${defaultProxy}`);
  } catch (err) {
    isSystemProxyBroken = true;
    console.log(`[PROXY STATUS] Active default adjustments complete: direct routing is enabled.`);
  }
}

