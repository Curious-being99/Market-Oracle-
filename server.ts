// Helper to validate and verify if a proxy string is a syntactically correct HTTP/HTTPS/SOCKS URL
function isValidProxyUrl(urlStr: any): boolean {
  if (!urlStr || typeof urlStr !== "string") return false;
  const trimmed = urlStr.trim();
  if (trimmed === "" || trimmed.toLowerCase() === "undefined" || trimmed.toLowerCase() === "null") return false;
  try {
    const parsed = new URL(trimmed);
    return parsed.protocol === "http:" || parsed.protocol === "https:" || parsed.protocol === "socks:" || parsed.protocol === "socks5:";
  } catch (e) {
    return false;
  }
}

// Custom proxied fetch supporting optional PROXY_URL or HTTP_PROXY environments automatically
async function fetchWithProxy(urlStr: string, options: any = {}): Promise<{ ok: boolean, status: number, json: () => Promise<any>, text: () => Promise<string> }> {
  // Directly bypass proxy if it has ever been reported broken
  if (isSystemProxyBroken) {
    return await fetch(urlStr, options);
  }

  const rawProxyUrl = memoryProxyUrl || (!isSystemProxyBroken ? (process.env.PROXY_URL || process.env.HTTP_PROXY) : null);
  const proxyUrl = isValidProxyUrl(rawProxyUrl) ? rawProxyUrl : null;
  
  if (!proxyUrl) {
    const res = await fetch(urlStr, options);
    return res;
  }
  
  return new Promise(async (resolve) => {
    let fallbackTriggered = false;
    
    async function triggerFallback(reason: string) {
      if (fallbackTriggered) return;
      fallbackTriggered = true;
      console.log(`[PROXY OPTIMIZE] Routing direct for ${urlStr} (Proxy ${proxyUrl} was unresponsive: ${reason})`);
      
      // Auto-pruning state updates
      if (proxyUrl === memoryProxyUrl) {
        console.log(`[PROXY ROTATOR] Dynamic proxy ${proxyUrl} bypassed. Routing standards active...`);
        memoryProxyUrl = null;
        const found = activeScrapedProxies.find(p => `${p.protocol}://${p.ip}:${p.port}` === proxyUrl);
        if (found) {
          found.status = "unresponsive";
        }
      } else if (proxyUrl === process.env.PROXY_URL || proxyUrl === process.env.HTTP_PROXY) {
        console.log(`[PROXY CONFIG] System default proxy ${proxyUrl} bypassed. Standard route in place.`);
        isSystemProxyBroken = true;
      }

      try {
        const res = await fetch(urlStr, options);
        resolve(res);
      } catch (err: any) {
        console.log(`[PROXY ADAPTIVE] Direct fallback completed for ${urlStr}: ${err.message || err}`);
        resolve({
          ok: false,
          status: 502,
          text: async () => `Standard direct route inactive: ${err.message || err}`,
          json: async () => ({ error: err.message || err })
        });
      }
    }

    try {
      const url = new URL(urlStr);
      const agent = createSafeHttpsProxyAgent(proxyUrl);
      const reqOpts = {
        method: options.method || "GET",
        headers: options.headers || {},
        agent: agent,
        timeout: 5000 // Increased from 2500 to 5000ms to tolerate slow proxy handshake
      };
      
      const req = https.request(url, reqOpts, (res: any) => {
        let rawData = "";
        res.on("data", (chunk: any) => {
          rawData += chunk;
        });
        res.on("end", () => {
          const status = res.statusCode || 200;
          resolve({
            ok: status >= 200 && status < 300,
            status,
            text: async () => rawData,
            json: async () => JSON.parse(rawData)
          });
        });
      });
      
      req.on("socket", (socket) => {
        socket.on("error", (err: any) => {
          triggerFallback(`socket issue: ${err.message || err}`);
        });
      });
      
      req.on("error", (err: any) => {
        triggerFallback(`connection issue: ${err.message || err}`);
      });
      
      req.on("timeout", () => {
        req.destroy();
        triggerFallback("timeout check");
      });
      
      if (options.body) {
        req.write(typeof options.body === "string" ? options.body : JSON.stringify(options.body));
      }
      req.end();
    } catch (e: any) {
      triggerFallback(`initialization: ${e.message || e}`);
    }
  });
}

