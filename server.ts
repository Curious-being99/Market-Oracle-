function processRealTrade(sym: string, price: number, size: number, side: "buy" | "sell", isPropagatedCall = false) {
  const state = symbolsState[sym];
  if (!state) return;

  // Track the timestamp of the last processed trade execution
  lastTradeTimes[sym] = Date.now();

  const oldPrice = state.currentPrice;
  state.anchorPrice = price;

  if (price !== oldPrice) {
    state.currentPrice = price;
    onPriceChange(sym, oldPrice, price);

    // Chain delta percentages of real crypto tickers directly to other assets
    // Omitted logic that propagated synthetic delta percentages

  }

  // If the asset does not support real volume block feeds, we omit it
  if (!state.hasRealVolume) return;

  // Propagation across all temporal resolutions
  Object.keys(state.footprintCache).forEach(tfStr => {
     const tf = parseInt(tfStr);
     const cache = state.footprintCache[tf];
     if (!cache || cache.length === 0) return;

     const activeBar = cache[cache.length - 1];
     activeBar.high = Math.max(activeBar.high, price);
     activeBar.low = Math.min(activeBar.low, price);
     activeBar.close = price;

     let row = activeBar.rows.find(r => Math.abs(r.price - price) < state.pipSize * 0.4);

     let finalVol = size;

     if (row) {
       if (side === "sell") {
         row.bidVolume += finalVol; 
       } else {
         row.askVolume += finalVol;
       }
       row.isImbalanceBuy = row.askVolume > row.bidVolume * 2.5 && row.askVolume > 50;
       row.isImbalanceSell = row.bidVolume > row.askVolume * 2.5 && row.bidVolume > 50;
     } else {
       const exactMatch = activeBar.rows.find(r => r.price === price);
       if (exactMatch) {
         if (side === "sell") exactMatch.bidVolume += finalVol;
         else exactMatch.askVolume += finalVol;
       } else {
         activeBar.rows.unshift({
           price: price,
           bidVolume: side === "sell" ? finalVol : 0,
           askVolume: side === "buy" ? finalVol : 0,
           isImbalanceBuy: false,
           isImbalanceSell: false
         });
         activeBar.rows.sort((a, b) => b.price - a.price);
       }
     }
     activeBar.totalVolume += finalVol;
  });

  // Seamless natural CVD aggregate impact
  const cvdDelta = (side === "sell" ? -size : size);
  updateCVD(sym, price, cvdDelta);
}

