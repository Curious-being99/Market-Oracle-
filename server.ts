// Update symbol anchor price from live external feeds.
// Centering footprint charts and restarting DOM cleanly if there is a massive drift.
function updateSymbolAnchor(symbol: string, rate: number, bid?: number, ask?: number) {
  const state = symbolsState[symbol];
  if (!state || !rate) return;

  const isFirst = !state.anchorPrice;
  const oldPrice = state.currentPrice;
  const deviation = Math.abs(oldPrice - rate);
  const tooFar = deviation > state.pipSize * 60; // 60 pips drift invalidates old baseline

  state.anchorPrice = rate;

  if (bid && ask) {
    const baseVol = getInitialStableSize(symbol) * 5;
    const decs = state.decimals;
    const bids = [{ price: Number(bid.toFixed(decs)), size: baseVol, mySize: 0 }];
    const asks = [{ price: Number(ask.toFixed(decs)), size: baseVol, mySize: 0 }];
    state.dom = { bids, asks };
    state.majorLiquidityPools = [
      { id: `${symbol}_buy_1`, price: bids[0].price, size: bids[0].size, side: "buy" },
      { id: `${symbol}_sell_1`, price: asks[0].price, size: asks[0].size, side: "sell" }
    ];
  }

  if (isFirst || tooFar) {
    state.currentPrice = rate;

    // Regrow all caches completely centered around the brand new baseline rate!
    state.footprintCache = {};
    [1].forEach(tf => {
      state.footprintCache[tf] = [];
      generateInitialFootprints(symbol, tf);
    });
    state.footprints = state.footprintCache[state.timeframe || 1];
    
    reanchorLiquidityPools(symbol);
    updateDOM(symbol);
  } else if (oldPrice !== rate) {
    const side = rate >= oldPrice ? "buy" : "sell";
    // Do not inject synthetic randomized tick volumes.
    processRealTrade(symbol, rate, 1, side);
  }
}

